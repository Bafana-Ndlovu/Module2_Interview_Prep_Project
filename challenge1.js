// Var - is a variable keyword that was used in olden days of javascript for declaration.
// Var is block scope that lives inside the block scope.
var name = "syntax"; // var variable

// Let - is also a variable declaration and initialization that lets you assign another variable at the later stage.

let userName = "Bafana";

// Later stage can assign another variable

let userName = "David";

// Const - is that variable always remains unchange it cant be re - assigned.

const month = "September";

// Eight Variable Examples

let myName = "Bafana"; // String data type
const number = 29; // number data type
let isEnjoying = true; // boolean
let price = 40.99; // floating data type
let empty_space = null;
let MAX_SAFE_INTEGER = 100;
